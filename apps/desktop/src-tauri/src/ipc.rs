use tauri::Wry;
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands, collect_events};

use crate::commands::{containers, domains, engine, metrics, settings, streams, welcome};
use crate::events::{DockerChanged, EngineChanged, MetricsUpdated, Navigate};

/// Every command and event the UI can use. `bindings.ts` is generated from this list.
pub(crate) fn builder() -> Builder<Wry> {
    Builder::<Wry>::new()
        .error_handling(ErrorHandlingMode::Throw)
        .typ::<crate::error::CommandError>()
        .commands(collect_commands![
            streams::stream_cancel,
            engine::engine_status,
            engine::engine_start,
            engine::engine_stop,
            engine::engine_restart,
            engine::engine_save_config,
            metrics::metrics_latest,
            metrics::metrics_history,
            settings::preferences_get,
            settings::preferences_set,
            settings::host_info,
            settings::about,
            settings::window_show_main,
            settings::app_quit,
            welcome::docker_desktop_detect,
            welcome::docker_desktop_import_images,
            containers::containers_list,
            containers::container_act,
            containers::container_stats,
            domains::domains_status,
            domains::domains_set_enabled,
            domains::domains_add_route,
            domains::domains_remove_route,
            domains::domains_install_resolver,
            domains::domains_uninstall_resolver,
            domains::domains_trust_ca,
            domains::domains_untrust_ca,
        ])
        .events(collect_events![EngineChanged, DockerChanged, MetricsUpdated, Navigate])
}

#[cfg(test)]
mod tests {
    use specta_typescript::Typescript;

    /// Regenerates the UI's bindings. CI fails if the committed file differs.
    #[test]
    fn export_bindings() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/lib/ipc/bindings.ts");
        super::builder()
            .export(
                Typescript::default().header("// Generated by tauri-specta. Do not edit.\n"),
                path,
            )
            .unwrap();
    }
}
