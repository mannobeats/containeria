use tauri::Wry;
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands, collect_events};

use crate::commands::{containers, engine, images, metrics, networks, streams, volumes};
use crate::events::{DockerChanged, EngineChanged, MetricsUpdated};

/// Every command and event the UI can use. `bindings.ts` is generated from this list.
pub(crate) fn builder() -> Builder<Wry> {
    Builder::<Wry>::new()
        .error_handling(ErrorHandlingMode::Throw)
        .typ::<crate::error::CommandError>()
        .commands(collect_commands![
            streams::stream_cancel,
            engine::engine_status,
            engine::engine_start,
            engine::engine_stop,
            engine::engine_restart,
            engine::engine_save_config,
            metrics::metrics_latest,
            containers::containers_list,
            containers::container_act,
            containers::container_stats,
            images::images_list,
            images::image_detail,
            images::image_pull,
            images::image_remove,
            images::image_tag,
            images::images_prune,
            images::hub_search,
            volumes::volumes_list,
            volumes::volume_create,
            volumes::volume_remove,
            volumes::volumes_prune,
            volumes::volume_files,
            volumes::volume_download,
            volumes::volume_backup,
            volumes::volume_clone,
            networks::networks_list,
            networks::network_detail,
            networks::network_create,
            networks::network_remove,
            networks::network_connect,
            networks::network_disconnect,
        ])
        .events(collect_events![EngineChanged, DockerChanged, MetricsUpdated])
}

#[cfg(test)]
mod tests {
    use specta_typescript::Typescript;

    /// Regenerates the UI's bindings. CI fails if the committed file differs.
    #[test]
    fn export_bindings() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/lib/ipc/bindings.ts");
        super::builder()
            .export(
                Typescript::default().header("// Generated by tauri-specta. Do not edit.\n"),
                path,
            )
            .unwrap();
    }
}
